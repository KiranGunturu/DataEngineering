--11) CALCULATE NO OF WEEKENDS IN A MONTH

WITH THIS_MONTH AS (
SELECT TRUNC (SYSDATE, 'MM')+LEVEL - 1 AS CDATE
FROM DUAL
CONNECT BY LEVEL <= LAST_DAY (TRUNC(SYSDATE,'MM')) - TRUNC(SYSDATE, 'MM') + 1)
SELECT COUNT(CDATE) AS TOTALWEEKENDS
FROM THIS_MONTH
WHERE TRIM(TO_CHAR(CDATE, 'DAY')) IN ('SATURDAY', 'SUNDAY');


