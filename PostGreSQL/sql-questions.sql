--3) HOW TO REMOVE DUPLICATE ROWS FROM TABLE?

--ONE WAY

DELETE FROM EMPPLOYEE
WHERE ROWID NOT IN
(SELECT MAX(ROWID) FROM EMPPLOYEE GROUP BY ID);

--SECOND WAY

DELETE FROM EMPPLOYEE WHERE ROWID IN
               (
                 SELECT RID FROM
                  (
                    SELECT ROWID RID,
                      ROW_NUMBER() OVER(PARTITION BY ID ORDER BY ID) RN
                      FROM EMPPLOYEE
                  )
                WHERE RN > 1
               );
			   

-- THIRD WAY

DELETE FROM EMPPLOYEE E1
         WHERE ROWID NOT IN
          (SELECT MAX(ROWID) FROM EMPPLOYEE E2
           WHERE E1.ID = E2.ID ); 
		   
		   
